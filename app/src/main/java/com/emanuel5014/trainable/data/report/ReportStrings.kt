package com.emanuel5014.trainable.data.report

/**
 * The words of the HTML report in the language of the app. A report is a file that travels, so it carries its own
 * text instead of pointing at the app's resources; a word missing from a language falls back to English.
 */
internal class ReportStrings private constructor(
    /** Language the page is written in, for its `lang` attribute. */
    val languageTag: String,
    private val values: Map<String, String>
) {
    operator fun get(key: String): String = values[key] ?: ENGLISH[key] ?: key

    companion object {
        fun forLanguage(languageCode: String): ReportStrings = when (languageCode.substringBefore('-').lowercase()) {
            "it" -> ReportStrings("it", ITALIAN)
            "es" -> ReportStrings("es", SPANISH)
            "fr" -> ReportStrings("fr", FRENCH)
            "de" -> ReportStrings("de", GERMAN)
            "pt" -> ReportStrings("pt", PORTUGUESE)
            else -> ReportStrings("en", ENGLISH)
        }
    }
}

